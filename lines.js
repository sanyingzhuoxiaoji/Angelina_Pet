const lastIndex = {};

function pick(category) {
  const pool = LINES[category];
  if (!pool || !pool.length) return '';
  if (pool.length === 1) return pool[0];
  let i;
  do {
    i = Math.floor(Math.random() * pool.length);
  } while (i === lastIndex[category]);
  lastIndex[category] = i;
  return pool[i];
}

